function noteApiCall(label) {
  const now = Date.now();

  const session = state.calls.get(label) || { count: 0, last: null };
  session.count += 1;
  session.last = now;
  state.calls.set(label, session);

  const total = state.installCalls.get(label) || { count: 0, last: null };
  total.count += 1;
  total.last = now;
  state.installCalls.set(label, total);
  saveInstallCalls();
}

async function getJson(url, signal) {
  try { noteApiCall(API_LABELS[new URL(url).host] || 'Other'); } catch { /* ignore */ }
  const res = await fetch(url, { cache: 'no-store', signal });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

/* Citybus publishes ETAs per stop, not per route. The batch Stop-ETA
   endpoint is the one that carries live data; the per-route endpoint
   returns an empty list. One request covers every route at a stop, so
   results are shared between cards and reused for a few seconds. */
const CTB_STOP_TTL = 8000;
const ctbStops = new Map(); // stop_id -> { at, promise }

function ctbStopEta(stopId) {
  const now = Date.now();
  const hit = ctbStops.get(stopId);
  if (hit && now - hit.at < CTB_STOP_TTL) return hit.promise;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 12000);
  const promise = getJson(`${CTB_API}/v1/transport/batch/stop-eta/CTB/${stopId}`, controller.signal)
    .then((body) => (Array.isArray(body.data) ? body.data : []))
    .finally(() => clearTimeout(timer));

  ctbStops.set(stopId, { at: now, promise });
  promise.catch(() => ctbStops.delete(stopId));
  return promise;
}

/* TfL arrivals for a whole line cover every stop on it. Fetching one
   response per line keeps the London page well inside TfL's
   unauthenticated rate limit. */
const TFL_LINE_TTL = 20000;
const TFL_BACKOFF_MS = 60000;
let tflBackoffUntil = 0;
const tflLines = new Map(); // line -> { at, promise }

function tflLineArrivals(line) {
  const now = Date.now();
  const hit = tflLines.get(line);
  if (hit && now - hit.at < TFL_LINE_TTL) return hit.promise;
  /* After a 429, stop hammering TfL and keep the last good arrivals. */
  if (now < tflBackoffUntil && hit && hit.rows) return Promise.resolve(hit.rows);

  const entry = { at: now, rows: hit ? hit.rows : null, promise: null };
  const controller = new AbortController();
  /* TfL occasionally answers in 6-9 s; cap it so one slow line cannot hold
     the whole refresh, and fall back to the last good rows. */
  const timer = setTimeout(() => controller.abort(), 10000);

  const load = (attempt) => getJson(`${TFL_API}/Line/${line}/Arrivals`, controller.signal)
    .then((rows) => (Array.isArray(rows) ? rows : []))
    .catch((err) => {
      if (controller.signal.aborted) {
        if (entry.rows) return entry.rows;
        throw err;
      }
      if (/429/.test(String(err && err.message))) {
        tflBackoffUntil = Date.now() + TFL_BACKOFF_MS;
        if (entry.rows) return entry.rows;
        throw err;
      }
      if (attempt === 0) {
        return new Promise((resolve) => setTimeout(resolve, 2000)).then(() => load(1));
      }
      /* Any other failure: keep showing the last good data. */
      if (entry.rows) return entry.rows;
      throw err;
    });

  entry.promise = load(0)
    .then((rows) => {
      entry.rows = rows;
      return rows;
    })
    .catch((err) => {
      tflLines.delete(line);
      throw err;
    })
    .finally(() => clearTimeout(timer));

  tflLines.set(line, entry);
  return entry.promise;
}

/* GMB and KMB have no server-side batching, so a first-visit page fetch can
   race the 30 s refresh. Share the in-flight promise per route + stop. */
const etaInflight = new Map();

function fetchEta(page, route, stop) {
  if (page.api !== 'gmb' && page.api !== 'kmb') return fetchEtaLive(page, route, stop);
  const key = keyOf(page, route, stop);
  const hit = etaInflight.get(key);
  if (hit) return hit;
  const promise = fetchEtaLive(page, route, stop).finally(() => {
    if (etaInflight.get(key) === promise) etaInflight.delete(key);
  });
  etaInflight.set(key, promise);
  return promise;
}

async function fetchEtaLive(page, route, stop) {
  const key = keyOf(page, route, stop);

  if (page.api === 'gmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    try {
      const body = await getJson(
        `${GMB_API}/eta/route-stop/${route.route_id}/${route.route_seq}/${stop.seq}`,
        controller.signal,
      );
      const data = body.data || {};
      state.etas.set(key, {
        enabled: data.enabled !== false,
        desc: data.description_en || '',
        list: (Array.isArray(data.eta) ? data.eta : []).map((entry) => ({
          ...entry,
          timeZone: HK_TZ,
        })),
        at: Date.now(),
      });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'kmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    const dirCode = route.direction === 'inbound' ? 'I' : 'O';
    try {
      const body = await getJson(
        `${KMB_API}/eta/${stop.stop_id}/${route.route}/${route.service_type}`,
        controller.signal,
      );
      const rows = Array.isArray(body.data) ? body.data : [];
      /* Match the stop sequence, direction and service type so other
         directions or short-workings at the same pole do not leak in. */
      const matched = rows
        .filter((row) => row.route === route.route
          && row.dir === dirCode
          && Number(row.service_type) === Number(route.service_type)
          && Number(row.seq) === Number(stop.seq)
          && row.eta)
        .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

      const dest = matched.length ? (matched[0].dest_en || '') : '';
      const list = matched
        .filter((row) => (row.dest_en || '') === dest)
        .map((row) => {
          const remark = row.rmk_en || row.rmk_tc || '';
          return {
            timestamp: row.eta,
            timeZone: HK_TZ,
            remarks: remark,
            scheduled: /scheduled/i.test(remark) || remark.includes('原定'),
          };
        });

      state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'tfl') {
    try {
      const rows = await tflLineArrivals(route.line);
      const target = route.towards.toLowerCase();
      const matched = rows
        .filter((row) => row.lineName === route.line
          && row.naptanId === stop.stop_id
          && (row.destinationName || '').toLowerCase().includes(target)
          && row.expectedArrival)
        .sort((a, b) => Date.parse(a.expectedArrival) - Date.parse(b.expectedArrival));

      const list = matched.map((row) => ({
        timestamp: row.expectedArrival,
        /* These are London buses; show London clock time even if the phone
           is in another timezone. */
        timeZone: LONDON_TZ,
        remarks: row.destinationName || '',
        vehicle: row.vehicleId || '',
        scheduled: false,
      }));

      state.etas.set(key, {
        enabled: true, desc: '', dest: route.towards, list, at: Date.now(),
      });
    } catch (err) {
      /* Keep the previous arrivals on screen rather than blanking the page;
         the status line reports the connection problem. */
      const previous = state.etas.get(key);
      if (!previous || !Array.isArray(previous.list) || !previous.list.length) {
        state.etas.set(key, {
          enabled: false,
          desc: 'London feed unavailable',
          list: [],
          at: Date.now(),
        });
      }
    }
    return;
  }

  const rows = await ctbStopEta(stop.stop_id);
  /* Match on stop sequence rather than the direction flag: Citybus labels
     the direction inconsistently, but `seq` follows the route-stop list.
     A few poles serve both directions, so keep the one arriving soonest
     and label the card with where those buses are going. */
  const matched = rows
    .filter((row) => row.route === route.route && row.seq === stop.seq && row.eta)
    .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

  const dest = matched.length ? (matched[0].dest || '') : '';
  const list = matched
    .filter((row) => (row.dest || '') === dest)
    .map((row) => ({
      timestamp: row.eta,
      timeZone: HK_TZ,
      remarks: row.rmk || '',
      /* Citybus has no scheduled/live flag in the open data. A scheduled
         trip is published on the exact minute; live GPS predictions carry
         seconds. */
      scheduled: isWholeMinute(row.eta),
    }));

  state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
}

async function fetchSegment(direction, route) {
  const key = `${direction.id}:${route.code}`;
  try {
    const [fromRows, toRows] = await Promise.all([
      ctbStopEta(direction.from.stop_id),
      ctbStopEta(direction.to.stop_id),
    ]);

    const pick = (rows, seq) => rows
      .filter((row) => row.route === route.route && row.seq === seq && row.eta)
      .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta))
      .map((row) => ({
        timestamp: row.eta,
        timeZone: HK_TZ,
        remarks: row.rmk || '',
        scheduled: isWholeMinute(row.eta),
      }));

    state.segments.set(key, {
      from: { enabled: true, desc: '', list: pick(fromRows, route.fromSeq) },
      to: { enabled: true, desc: '', list: pick(toRows, route.toSeq) },
      at: Date.now(),
    });
  } catch (err) {
    /* Keep the last good lists rather than blanking the page; the status
       line already reports the connection problem. */
    const previous = state.segments.get(key);
    if (previous) {
      state.segments.set(key, { ...previous, stale: true });
    } else {
      const failed = { enabled: false, desc: 'Citybus feed unavailable', list: [] };
      state.segments.set(key, { from: failed, to: failed, at: Date.now() });
    }
    throw err;
  }
}

/* Citybus and Taikoo load with the app; KMB, Minibuses and London fetch
   their first data only when the page is swiped to, then refresh normally. */
/* Only the static Info page is always rendered; every live page loads and
   refreshes only while it is the page on screen. */
function pageIsEager(page) {
  return page.api === 'info';
}

function pageIsLoaded(page) {
  return pageIsEager(page) || state.loaded.has(page.id);
}

function pageJobs(page) {
  const jobs = new Map();
  for (const route of page.routes || []) {
    for (const stop of route.bookmarks) {
      jobs.set(keyOf(page, route, stop), { page, route, stop });
    }
  }
  const near = state.nearest.get(page.id);
  if (near) {
    jobs.set(keyOf(page, near.route, near.stop), { page, route: near.route, stop: near.stop });
  }
  return [...jobs.values()];
}

/* Fetch just one page's stops: on first visit, or when it goes stale. */
async function fetchPage(page) {
  state.pageUpdated.set(page.id, Date.now());
  const segmentJobs = [];
  if (page.api === 'segment') {
    for (const direction of page.directions) {
      for (const route of direction.routes) segmentJobs.push({ direction, route });
    }
  }
  const results = await Promise.allSettled([
    ...pageJobs(page).map(({ page: owner, route, stop }) => fetchEta(owner, route, stop)),
    ...segmentJobs.map(({ direction, route }) => fetchSegment(direction, route)),
  ]);
  if (results.some((result) => result.status === 'fulfilled')) {
    state.lastUpdate = new Date();
    state.fromCache = false;
    saveSnapshot();
  }
  render();
}

/* First visit: fetch only this page, so the app loads just the page you
   are looking at. */
async function loadPage(page) {
  if (!page || page.api === 'info' || pageIsLoaded(page)) return;
  state.loaded.add(page.id);
  renderPage(page);
  await fetchPage(page);
}

/* A visited page swiped back to should not wait for the 30 s tick. */
function maybeRefreshPage(page) {
  if (!pageIsLoaded(page) || pageIsEager(page) || page.api === 'info') return;
  const at = state.pageUpdated.get(page.id) || 0;
  if (Date.now() - at < PAGE_STALE_MS) return;
  fetchPage(page);
}

let activateTimer = null;

function activateCurrentPage() {
  const page = PAGES[state.page];
  if (!page) return;
  if (!pageIsLoaded(page)) loadPage(page);
  else maybeRefreshPage(page);
}

/* Wait for the swipe (or tab jump) to settle so passing over pages on the
   way does not fetch each one. */
function scheduleActivation() {
  clearTimeout(activateTimer);
  activateTimer = setTimeout(activateCurrentPage, 150);
}

/* Only the page on screen polls. Nothing refreshes in the background. */
function pageIsLive(page) {
  if (!pageIsLoaded(page)) return false;
  const current = PAGES[state.page];
  return Boolean(current && current.id === page.id);
}

async function refresh(force = false) {
  if (state.busy) return;
  if (!force && state.lastUpdate && Date.now() - state.lastUpdate.getTime() < 5000) return;
  if (force) {
    ctbStops.clear();
    tflLines.clear();
  }
  state.busy = true;
  setBusy(true);

  const jobs = new Map();
  const segmentJobs = [];
  for (const page of PAGES) {
    if (!pageIsLive(page)) continue;
    if (page.api === 'segment') {
      for (const direction of page.directions) {
        for (const route of direction.routes) {
          segmentJobs.push({ direction, route });
        }
      }
      continue;
    }
    if (page.api === 'info') continue;
    for (const [key, job] of new Map(pageJobs(page).map((item) => [keyOf(item.page, item.route, item.stop), item]))) {
      jobs.set(key, job);
    }
  }

  const results = await Promise.allSettled([
    ...[...jobs.values()].map(({ page, route, stop }) => fetchEta(page, route, stop)),
    ...segmentJobs.map(({ direction, route }) => fetchSegment(direction, route)),
  ]);

  state.error = results.length > 0 && results.every((r) => r.status === 'rejected');
  state.lastUpdate = new Date();
  state.busy = false;
  setBusy(false);
  if (results.some((result) => result.status === 'fulfilled')) {
    for (const page of PAGES) {
      if (pageIsLive(page)) state.pageUpdated.set(page.id, Date.now());
    }
    state.fromCache = false;
    saveSnapshot();
  }
  render();
}

