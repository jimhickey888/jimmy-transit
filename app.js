async function getJson(url, signal) {
  const res = await fetch(url, { cache: 'no-store', signal });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

/* Citybus publishes ETAs per stop, not per route. The batch Stop-ETA
   endpoint is the one that carries live data; the per-route endpoint
   returns an empty list. One request covers every route at a stop, so
   results are shared between cards and reused for a few seconds. */
const CTB_STOP_TTL = 8000;
const ctbStops = new Map(); // stop_id -> { at, promise }

function ctbStopEta(stopId) {
  const now = Date.now();
  const hit = ctbStops.get(stopId);
  if (hit && now - hit.at < CTB_STOP_TTL) return hit.promise;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 12000);
  const promise = getJson(`${CTB_API}/v1/transport/batch/stop-eta/CTB/${stopId}`, controller.signal)
    .then((body) => (Array.isArray(body.data) ? body.data : []))
    .finally(() => clearTimeout(timer));

  ctbStops.set(stopId, { at: now, promise });
  promise.catch(() => ctbStops.delete(stopId));
  return promise;
}

/* TfL arrivals for a whole line cover every stop on it. Fetching one
   response per line keeps the London page well inside TfL's
   unauthenticated rate limit. */
const TFL_LINE_TTL = 20000;
const tflLines = new Map(); // line -> { at, promise }

function tflLineArrivals(line) {
  const now = Date.now();
  const hit = tflLines.get(line);
  if (hit && now - hit.at < TFL_LINE_TTL) return hit.promise;

  const entry = { at: now, rows: hit ? hit.rows : null, promise: null };
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);

  const load = (attempt) => getJson(`${TFL_API}/Line/${line}/Arrivals`, controller.signal)
    .then((rows) => (Array.isArray(rows) ? rows : []))
    .catch((err) => {
      if (attempt === 0) {
        return new Promise((resolve) => setTimeout(resolve, 2000)).then(() => load(1));
      }
      /* If TfL rate-limits us, keep showing the last good data. */
      if (entry.rows) return entry.rows;
      throw err;
    });

  entry.promise = load(0)
    .then((rows) => {
      entry.rows = rows;
      return rows;
    })
    .catch((err) => {
      tflLines.delete(line);
      throw err;
    })
    .finally(() => clearTimeout(timer));

  tflLines.set(line, entry);
  return entry.promise;
}

async function fetchEta(page, route, stop) {
  const key = keyOf(page, route, stop);

  if (page.api === 'gmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    try {
      const body = await getJson(
        `${GMB_API}/eta/route-stop/${route.route_id}/${route.route_seq}/${stop.seq}`,
        controller.signal,
      );
      const data = body.data || {};
      state.etas.set(key, {
        enabled: data.enabled !== false,
        desc: data.description_en || '',
        list: (Array.isArray(data.eta) ? data.eta : []).map((entry) => ({
          ...entry,
          timeZone: HK_TZ,
        })),
        at: Date.now(),
      });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'kmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    const dirCode = route.direction === 'inbound' ? 'I' : 'O';
    try {
      const body = await getJson(
        `${KMB_API}/eta/${stop.stop_id}/${route.route}/${route.service_type}`,
        controller.signal,
      );
      const rows = Array.isArray(body.data) ? body.data : [];
      /* Match the stop sequence, direction and service type so other
         directions or short-workings at the same pole do not leak in. */
      const matched = rows
        .filter((row) => row.route === route.route
          && row.dir === dirCode
          && Number(row.service_type) === Number(route.service_type)
          && Number(row.seq) === Number(stop.seq)
          && row.eta)
        .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

      const dest = matched.length ? (matched[0].dest_en || '') : '';
      const list = matched
        .filter((row) => (row.dest_en || '') === dest)
        .map((row) => {
          const remark = row.rmk_en || row.rmk_tc || '';
          return {
            timestamp: row.eta,
            timeZone: HK_TZ,
            remarks: remark,
            scheduled: /scheduled/i.test(remark) || remark.includes('原定'),
          };
        });

      state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'tfl') {
    try {
      const rows = await tflLineArrivals(route.line);
      const target = route.towards.toLowerCase();
      const matched = rows
        .filter((row) => row.lineName === route.line
          && row.naptanId === stop.stop_id
          && (row.destinationName || '').toLowerCase().includes(target)
          && row.expectedArrival)
        .sort((a, b) => Date.parse(a.expectedArrival) - Date.parse(b.expectedArrival));

      const list = matched.map((row) => ({
        timestamp: row.expectedArrival,
        /* These are London buses; show London clock time even if the phone
           is in another timezone. */
        timeZone: LONDON_TZ,
        remarks: row.destinationName || '',
        vehicle: row.vehicleId || '',
        scheduled: false,
      }));

      state.etas.set(key, {
        enabled: true, desc: '', dest: route.towards, list, at: Date.now(),
      });
    } catch (err) {
      state.etas.set(key, {
        enabled: false,
        desc: 'London feed unavailable',
        list: [],
        at: Date.now(),
      });
    }
    return;
  }

  const rows = await ctbStopEta(stop.stop_id);
  /* Match on stop sequence rather than the direction flag: Citybus labels
     the direction inconsistently, but `seq` follows the route-stop list.
     A few poles serve both directions, so keep the one arriving soonest
     and label the card with where those buses are going. */
  const matched = rows
    .filter((row) => row.route === route.route && row.seq === stop.seq && row.eta)
    .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

  const dest = matched.length ? (matched[0].dest || '') : '';
  const list = matched
    .filter((row) => (row.dest || '') === dest)
    .map((row) => ({
      timestamp: row.eta,
      timeZone: HK_TZ,
      remarks: row.rmk || '',
      /* Citybus has no scheduled/live flag in the open data. A scheduled
         trip is published on the exact minute; live GPS predictions carry
         seconds. */
      scheduled: isWholeMinute(row.eta),
    }));

  state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
}

async function fetchSegment(direction, route) {
  const key = `${direction.id}:${route.code}`;
  try {
    const [fromRows, toRows] = await Promise.all([
      ctbStopEta(direction.from.stop_id),
      ctbStopEta(direction.to.stop_id),
    ]);

    const pick = (rows, seq) => rows
      .filter((row) => row.route === route.route && row.seq === seq && row.eta)
      .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta))
      .map((row) => ({
        timestamp: row.eta,
        timeZone: HK_TZ,
        remarks: row.rmk || '',
        scheduled: isWholeMinute(row.eta),
      }));

    state.segments.set(key, {
      from: { enabled: true, desc: '', list: pick(fromRows, route.fromSeq) },
      to: { enabled: true, desc: '', list: pick(toRows, route.toSeq) },
      at: Date.now(),
    });
  } catch (err) {
    const failed = { enabled: false, desc: 'Citybus feed unavailable', list: [] };
    state.segments.set(key, { from: failed, to: failed, at: Date.now() });
    throw err;
  }
}

async function refresh(force = false) {
  if (state.busy) return;
  if (!force && state.lastUpdate && Date.now() - state.lastUpdate.getTime() < 5000) return;
  if (force) {
    ctbStops.clear();
    tflLines.clear();
  }
  state.busy = true;
  setBusy(true);

  const jobs = new Map();
  const segmentJobs = [];
  for (const page of PAGES) {
    if (page.api === 'segment') {
      for (const direction of page.directions) {
        for (const route of direction.routes) {
          segmentJobs.push({ direction, route });
        }
      }
      continue;
    }
    for (const route of page.routes) {
      for (const stop of route.bookmarks) {
        jobs.set(keyOf(page, route, stop), { page, route, stop });
      }
    }
    const near = state.nearest.get(page.id);
    if (near) {
      jobs.set(keyOf(page, near.route, near.stop), { page, route: near.route, stop: near.stop });
    }
  }

  const results = await Promise.allSettled([
    ...[...jobs.values()].map(({ page, route, stop }) => fetchEta(page, route, stop)),
    ...segmentJobs.map(({ direction, route }) => fetchSegment(direction, route)),
  ]);

  state.error = results.length > 0 && results.every((r) => r.status === 'rejected');
  state.lastUpdate = new Date();
  state.busy = false;
  setBusy(false);
  render();
}

