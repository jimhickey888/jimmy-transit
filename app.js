/* Live arrivals for green minibus 25 & 49M, Citybus 25, 25A, 27, 85 and
   KMB 108. Data: Transport Department eTA GMB API and data.gov.hk Citybus
   and KMB APIs. Route geometry and saved stops come from data.js
   (generated by bake.py). */

const GMB_API = 'https://data.etagmb.gov.hk';
const CTB_API = 'https://rt.data.gov.hk';
const KMB_API = 'https://data.etabus.gov.hk/v1/transport/kmb';
const TFL_API = 'https://api.tfl.gov.uk';
const HK_TZ = 'Asia/Hong_Kong';
const LONDON_TZ = 'Europe/London';

const APP_VERSION = '1.8.0';
const APP_BUILD = '22 Nov 2026, 00:10 HKT';

PAGES.push({
  id: 'info',
  title: 'Info',
  subtitle: 'Endpoints · Build',
  api: 'info',
  routes: [],
});
const REFRESH_MS = 30000;
const MAX_ETAS = 3;
const MOVE_THRESHOLD_M = 20;

const state = {
  etas: new Map(),     // key -> { enabled, desc, list, at }
  segments: new Map(), // segment route code -> { from, to, at }
  nearest: new Map(),  // page id -> { route, stop, dist }
  lastUpdate: null,
  error: false,
  busy: false,
  lastPos: null,
  page: 0,
};

function keyOf(page, route, stop) {
  if (page.api === 'gmb') {
    return `gmb:${route.route_id}/${route.route_seq}/${stop.seq}`;
  }
  if (page.api === 'kmb') {
    return `kmb:${route.route}/${route.service_type}/${route.direction}/${stop.seq}`;
  }
  if (page.api === 'tfl') {
    return `tfl:${route.line}/${route.towards}/${stop.stop_id}`;
  }
  return `ctb:${route.route}/${route.dirCode}/${stop.stop_id}`;
}

const esc = (value) => String(value).replace(/[&<>"']/g, (c) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[c]));

function minutesFrom(entry, now) {
  const t = Date.parse(entry && entry.timestamp);
  if (Number.isFinite(t)) return Math.round((t - now) / 60000);
  if (entry && typeof entry.diff === 'number') return entry.diff;
  return null;
}

function isWholeMinute(iso) {
  const t = Date.parse(iso);
  return Number.isFinite(t) && new Date(t).getSeconds() === 0;
}

function sortedEntries(list, now) {
  return list
    .map((entry) => {
      const m = minutesFrom(entry, now);
      if (m === null) return null;
      return { m, scheduled: !!entry.scheduled, time: clockFrom(entry) };
    })
    .filter(Boolean)
    .sort((a, b) => a.m - b.m);
}

function fmtClock(date, timeZone) {
  const options = {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  };
  if (timeZone) options.timeZone = timeZone;
  return date.toLocaleTimeString('en-GB', options);
}

function clockFrom(entry) {
  const t = Date.parse(entry && entry.timestamp);
  return Number.isFinite(t) ? fmtClock(new Date(t), entry && entry.timeZone) : '';
}

function fmtTime(date) {
  return date.toLocaleTimeString('en-GB', { hour12: false });
}

function fmtDistance(metres) {
  if (metres < 1000) return `${Math.max(10, Math.round(metres / 10) * 10)} m`;
  return `${(metres / 1000).toFixed(1)} km`;
}

function distanceM(a, b) {
  const R = 6371000;
  const rad = (x) => (x * Math.PI) / 180;
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
    + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/* ---------------- data ---------------- */

async function getJson(url, signal) {
  const res = await fetch(url, { cache: 'no-store', signal });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

/* Citybus publishes ETAs per stop, not per route. The batch Stop-ETA
   endpoint is the one that carries live data; the per-route endpoint
   returns an empty list. One request covers every route at a stop, so
   results are shared between cards and reused for a few seconds. */
const CTB_STOP_TTL = 8000;
const ctbStops = new Map(); // stop_id -> { at, promise }

function ctbStopEta(stopId) {
  const now = Date.now();
  const hit = ctbStops.get(stopId);
  if (hit && now - hit.at < CTB_STOP_TTL) return hit.promise;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 12000);
  const promise = getJson(`${CTB_API}/v1/transport/batch/stop-eta/CTB/${stopId}`, controller.signal)
    .then((body) => (Array.isArray(body.data) ? body.data : []))
    .finally(() => clearTimeout(timer));

  ctbStops.set(stopId, { at: now, promise });
  promise.catch(() => ctbStops.delete(stopId));
  return promise;
}

/* TfL arrivals for a whole line cover every stop on it. Fetching one
   response per line keeps the London page well inside TfL's
   unauthenticated rate limit. */
const TFL_LINE_TTL = 20000;
const tflLines = new Map(); // line -> { at, promise }

function tflLineArrivals(line) {
  const now = Date.now();
  const hit = tflLines.get(line);
  if (hit && now - hit.at < TFL_LINE_TTL) return hit.promise;

  const entry = { at: now, rows: hit ? hit.rows : null, promise: null };
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);

  const load = (attempt) => getJson(`${TFL_API}/Line/${line}/Arrivals`, controller.signal)
    .then((rows) => (Array.isArray(rows) ? rows : []))
    .catch((err) => {
      if (attempt === 0) {
        return new Promise((resolve) => setTimeout(resolve, 2000)).then(() => load(1));
      }
      /* If TfL rate-limits us, keep showing the last good data. */
      if (entry.rows) return entry.rows;
      throw err;
    });

  entry.promise = load(0)
    .then((rows) => {
      entry.rows = rows;
      return rows;
    })
    .catch((err) => {
      tflLines.delete(line);
      throw err;
    })
    .finally(() => clearTimeout(timer));

  tflLines.set(line, entry);
  return entry.promise;
}

async function fetchEta(page, route, stop) {
  const key = keyOf(page, route, stop);

  if (page.api === 'gmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    try {
      const body = await getJson(
        `${GMB_API}/eta/route-stop/${route.route_id}/${route.route_seq}/${stop.seq}`,
        controller.signal,
      );
      const data = body.data || {};
      state.etas.set(key, {
        enabled: data.enabled !== false,
        desc: data.description_en || '',
        list: (Array.isArray(data.eta) ? data.eta : []).map((entry) => ({
          ...entry,
          timeZone: HK_TZ,
        })),
        at: Date.now(),
      });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'kmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    const dirCode = route.direction === 'inbound' ? 'I' : 'O';
    try {
      const body = await getJson(
        `${KMB_API}/eta/${stop.stop_id}/${route.route}/${route.service_type}`,
        controller.signal,
      );
      const rows = Array.isArray(body.data) ? body.data : [];
      /* Match the stop sequence, direction and service type so other
         directions or short-workings at the same pole do not leak in. */
      const matched = rows
        .filter((row) => row.route === route.route
          && row.dir === dirCode
          && Number(row.service_type) === Number(route.service_type)
          && Number(row.seq) === Number(stop.seq)
          && row.eta)
        .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

      const dest = matched.length ? (matched[0].dest_en || '') : '';
      const list = matched
        .filter((row) => (row.dest_en || '') === dest)
        .map((row) => {
          const remark = row.rmk_en || row.rmk_tc || '';
          return {
            timestamp: row.eta,
            timeZone: HK_TZ,
            remarks: remark,
            scheduled: /scheduled/i.test(remark) || remark.includes('原定'),
          };
        });

      state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  if (page.api === 'tfl') {
    try {
      const rows = await tflLineArrivals(route.line);
      const target = route.towards.toLowerCase();
      const matched = rows
        .filter((row) => row.lineName === route.line
          && row.naptanId === stop.stop_id
          && (row.destinationName || '').toLowerCase().includes(target)
          && row.expectedArrival)
        .sort((a, b) => Date.parse(a.expectedArrival) - Date.parse(b.expectedArrival));

      const list = matched.map((row) => ({
        timestamp: row.expectedArrival,
        /* These are London buses; show London clock time even if the phone
           is in another timezone. */
        timeZone: LONDON_TZ,
        remarks: row.destinationName || '',
        scheduled: false,
      }));

      state.etas.set(key, {
        enabled: true, desc: '', dest: route.towards, list, at: Date.now(),
      });
    } catch (err) {
      state.etas.set(key, {
        enabled: false,
        desc: 'London feed unavailable',
        list: [],
        at: Date.now(),
      });
    }
    return;
  }

  const rows = await ctbStopEta(stop.stop_id);
  /* Match on stop sequence rather than the direction flag: Citybus labels
     the direction inconsistently, but `seq` follows the route-stop list.
     A few poles serve both directions, so keep the one arriving soonest
     and label the card with where those buses are going. */
  const matched = rows
    .filter((row) => row.route === route.route && row.seq === stop.seq && row.eta)
    .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

  const dest = matched.length ? (matched[0].dest || '') : '';
  const list = matched
    .filter((row) => (row.dest || '') === dest)
    .map((row) => ({
      timestamp: row.eta,
      timeZone: HK_TZ,
      remarks: row.rmk || '',
      /* Citybus has no scheduled/live flag in the open data. A scheduled
         trip is published on the exact minute; live GPS predictions carry
         seconds. */
      scheduled: isWholeMinute(row.eta),
    }));

  state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
}

async function fetchSegment(route) {
  try {
    const [fromRows, toRows] = await Promise.all([
      ctbStopEta(route.from.stop_id),
      ctbStopEta(route.to.stop_id),
    ]);

    const pick = (rows, seq) => rows
      .filter((row) => row.route === route.route && row.seq === seq && row.eta)
      .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta))
      .map((row) => ({
        timestamp: row.eta,
        timeZone: HK_TZ,
        remarks: row.rmk || '',
        scheduled: isWholeMinute(row.eta),
      }));

    state.segments.set(route.code, {
      from: { enabled: true, desc: '', list: pick(fromRows, route.fromSeq) },
      to: { enabled: true, desc: '', list: pick(toRows, route.toSeq) },
      at: Date.now(),
    });
  } catch (err) {
    const failed = { enabled: false, desc: 'Citybus feed unavailable', list: [] };
    state.segments.set(route.code, { from: failed, to: failed, at: Date.now() });
    throw err;
  }
}

async function refresh(force = false) {
  if (state.busy) return;
  if (!force && state.lastUpdate && Date.now() - state.lastUpdate.getTime() < 5000) return;
  if (force) {
    ctbStops.clear();
    tflLines.clear();
  }
  state.busy = true;
  setBusy(true);

  const jobs = new Map();
  const segmentRoutes = [];
  for (const page of PAGES) {
    if (page.api === 'segment') {
      segmentRoutes.push(...page.routes);
      continue;
    }
    for (const route of page.routes) {
      for (const stop of route.bookmarks) {
        jobs.set(keyOf(page, route, stop), { page, route, stop });
      }
    }
    const near = state.nearest.get(page.id);
    if (near) {
      jobs.set(keyOf(page, near.route, near.stop), { page, route: near.route, stop: near.stop });
    }
  }

  const results = await Promise.allSettled([
    ...[...jobs.values()].map(({ page, route, stop }) => fetchEta(page, route, stop)),
    ...segmentRoutes.map((route) => fetchSegment(route)),
  ]);

  state.error = results.length > 0 && results.every((r) => r.status === 'rejected');
  state.lastUpdate = new Date();
  state.busy = false;
  setBusy(false);
  render();
}

/* ---------------- nearest stop ---------------- */

function computeNearest(page, pos) {
  let best = null;
  const seen = new Set();

  for (const route of page.routes) {
    for (const stop of route.stops) {
      if (seen.has(stop.stop_id)) continue;
      seen.add(stop.stop_id);
      if (typeof stop.lat !== 'number' || typeof stop.lon !== 'number') continue;
      const dist = distanceM(pos, { lat: stop.lat, lon: stop.lon });
      if (!best || dist < best.dist) best = { route, stop, dist };
    }
  }
  return best;
}

async function updateNearest(pos) {
  const pending = [];

  for (const page of PAGES) {
    if (page.api === 'segment') continue;
    const next = computeNearest(page, pos);
    if (!next) continue;

    const prev = state.nearest.get(page.id);
    const changed = !prev || prev.route !== next.route || prev.stop !== next.stop;
    state.nearest.set(page.id, next);
    if (!changed) continue;

    const cached = state.etas.get(keyOf(page, next.route, next.stop));
    if (!cached || Date.now() - cached.at > REFRESH_MS - 5000) {
      pending.push(fetchEta(page, next.route, next.stop).catch(() => {
        /* keep showing the strip without a time */
      }));
    }
  }

  render();
  if (pending.length) Promise.allSettled(pending).then(render);
}

function startGeolocation() {
  if (!('geolocation' in navigator)) return;

  navigator.geolocation.watchPosition(
    (position) => {
      const pos = {
        lat: position.coords.latitude,
        lon: position.coords.longitude,
      };
      if (state.lastPos && distanceM(state.lastPos, pos) < MOVE_THRESHOLD_M) return;
      state.lastPos = pos;
      updateNearest(pos);
    },
    () => {
      state.lastPos = null;
      if (state.nearest.size) {
        state.nearest.clear();
        render();
      }
    },
    { enableHighAccuracy: true, maximumAge: 60000, timeout: 20000 },
  );
}

/* ---------------- rendering ---------------- */

function etaPills(cached) {
  if (!cached) return '<span class="empty">Loading…</span>';
  if (!cached.enabled) return `<span class="empty">${esc(cached.desc || 'Not available')}</span>`;

  const entries = sortedEntries(cached.list, Date.now()).slice(0, MAX_ETAS);
  if (!entries.length) return '<span class="empty">No arrivals right now</span>';

  return entries.map(({ m, scheduled, time }, i) => {
    const classes = ['eta'];
    if (scheduled) classes.push('sched');
    else if (i === 0) classes.push('first');
    if (m <= 0 && !scheduled) classes.push('due');

    const cls = classes.join(' ');
    const title = scheduled ? 'Scheduled time' : 'Live arrival';
    const timeHtml = time ? `<span class="eta-time">${esc(time)}</span>` : '';

    if (m <= 0) {
      return `<span class="${cls}" title="${title}"><span class="eta-main">Due</span>${timeHtml}</span>`;
    }
    return `<span class="${cls}" title="${title}"><span class="eta-main"><b>${m}</b><small>min</small></span>${timeHtml}</span>`;
  }).join('');
}

function etasHtml(page, route, stop) {
  return etaPills(state.etas.get(keyOf(page, route, stop)));
}

function stopPoint(route, stop) {
  const point = route.stops.find(
    (s) => s.seq === stop.seq && s.stop_id === stop.stop_id,
  );
  if (!point || typeof point.lat !== 'number' || typeof point.lon !== 'number') return null;
  return { lat: point.lat, lon: point.lon };
}

/* Straight-line distance from the last known position to a stop group. */
function groupDistance(group) {
  if (!state.lastPos) return null;
  for (const { route, stop } of group.routes) {
    const point = stopPoint(route, stop);
    if (point) return distanceM(state.lastPos, point);
  }
  return null;
}

function directionOf(page, route, stop) {
  if (route.towards) return route.towards;
  const cached = state.etas.get(keyOf(page, route, stop));
  if (cached && cached.dest) return cached.dest;
  return route.dest || route.direction || '';
}

/* Normalise destination strings so variants of the same direction (for
   example “Braemar Hill” and “Braemar Hill / North Point”) group
   together, while genuinely different directions stay apart. */
function directionKey(direction) {
  return direction
    .toLowerCase()
    .replace(/\([^)]*\)/g, ' ')
    .split(/[\/,]/)[0]
    .replace(/\s+/g, ' ')
    .trim();
}

function directionLabel(route, direction) {
  if (route.towards) return `towards ${route.towards}`;
  return direction ? `→ ${direction}` : '';
}

/* Citybus destinations come from the live rows; until those arrive we do
   not know which way the buses at a stop are heading, so leave the label
   blank rather than guessing from the route's terminal. */
function groupLabel(page, route, stop, direction) {
  if (page.api === 'ctb') {
    const cached = state.etas.get(keyOf(page, route, stop));
    if (!cached || !cached.dest) return '';
  }
  return directionLabel(route, direction);
}

function stopGroups(page) {
  const groups = new Map();
  const stopOrder = new Map();

  for (const route of page.routes) {
    for (const stop of route.bookmarks) {
      if (!stopOrder.has(stop.stop_id)) stopOrder.set(stop.stop_id, stopOrder.size);

      const direction = directionOf(page, route, stop);
      const groupKey = `${stop.stop_id}::${directionKey(direction)}`;
      let group = groups.get(groupKey);
      if (!group) {
        group = {
          stop_id: stop.stop_id,
          name: stop.name,
          label: groupLabel(page, route, stop, direction),
          order: groups.size,
          routes: [],
        };
        groups.set(groupKey, group);
      }
      if (!group.routes.some((entry) => entry.route === route && entry.stop === stop)) {
        group.routes.push({ route, stop });
      }
    }
  }

  const sorted = [...groups.values()].sort((a, b) => (
    stopOrder.get(a.stop_id) - stopOrder.get(b.stop_id) || a.order - b.order
  ));

  if (page.stopOrder) {
    const rank = new Map(page.stopOrder.map((name, i) => [name, i]));
    const fallback = page.stopOrder.length;
    sorted.sort((a, b) => {
      const ra = rank.has(a.name) ? rank.get(a.name) : fallback;
      const rb = rank.has(b.name) ? rank.get(b.name) : fallback;
      return ra - rb;
    });
  }

  return sorted;
}

function nearestHtml(page) {
  const near = state.nearest.get(page.id);
  if (!near) return '';

  const { route, stop, dist } = near;
  const cached = state.etas.get(keyOf(page, route, stop));
  let eta = '…';
  let etaTime = '';
  let scheduled = false;

  if (cached) {
    if (!cached.enabled) {
      eta = '—';
    } else {
      const entries = sortedEntries(cached.list, Date.now());
      if (!entries.length) {
        eta = '—';
      } else {
        eta = entries[0].m <= 0 ? 'Due' : `${entries[0].m} min`;
        etaTime = entries[0].time;
        scheduled = entries[0].scheduled;
      }
    }
  }

  return `
    <div class="nearest">
      <svg class="pin" viewBox="0 0 24 24" fill="none" stroke="currentColor"
           stroke-width="1.8" stroke-linejoin="round" aria-hidden="true">
        <path d="M12 21s-6.5-5.8-6.5-10.5a6.5 6.5 0 1 1 13 0C18.5 15.2 12 21 12 21z"/>
        <circle cx="12" cy="10.4" r="2.3"/>
      </svg>
      <div class="nearest-main">
        <div class="nearest-stop">${esc(route.code)} · ${esc(stop.name)}</div>
        <div class="nearest-dist">${fmtDistance(dist)} away</div>
      </div>
      <div class="nearest-eta${scheduled ? ' sched' : ''}">
        <span class="nearest-eta-main">${esc(eta)}</span>
        ${etaTime ? `<span class="nearest-eta-time">${esc(etaTime)}</span>` : ''}
      </div>
    </div>`;
}

function sourceLine(page) {
  if (page.api === 'gmb') {
    return 'Real-time data from the Transport Department<br>eTA GMB service';
  }
  if (page.api === 'kmb') {
    return 'Real-time data from data.gov.hk<br>KMB';
  }
  if (page.api === 'tfl') {
    return 'Real-time data from TfL<br>London Buses';
  }
  return 'Real-time data from data.gov.hk<br>Citybus';
}

function segmentHtml(page) {
  const from = page.from || page.routes[0].from;
  const to = page.to || page.routes[0].to;
  const blocks = [
    { stop: from, label: '→ New Trend Plaza', field: 'from' },
    { stop: to, label: '← Taikoo Place', field: 'to' },
  ];

  let html = `<p class="segment-note">Next departures from Taikoo Place and arrivals at New Trend Plaza.</p>`;

  for (const block of blocks) {
    const point = (typeof block.stop.lat === 'number' && typeof block.stop.lon === 'number')
      ? { lat: block.stop.lat, lon: block.stop.lon }
      : null;
    const dist = state.lastPos && point ? distanceM(state.lastPos, point) : null;
    const meta = [
      block.label,
      Number.isFinite(dist) ? `${fmtDistance(dist)} away` : '',
    ].filter(Boolean).join(' · ');

    html += `
      <section class="stop-group">
        <div class="stop-group-head">
          <div class="stop-group-main">
            <div class="stop-group-name">${esc(block.stop.name)}</div>
            <div class="stop-group-dir">${esc(meta)}</div>
          </div>
          <div class="stop-group-id">Stop ${esc(block.stop.stop_id)}</div>
        </div>
        <article class="card shared">
          ${page.routes.map((route) => {
            const cache = state.segments.get(route.code);
            const list = cache ? cache[block.field] : null;
            return `
              <div class="route-row">
                <span class="badge">${esc(route.code)}</span>
                <div class="etas">${etaPills(list)}</div>
              </div>`;
          }).join('')}
        </article>
      </section>`;
  }

  html += `<footer class="foot"><p>${sourceLine(page)}</p></footer>`;
  return html;
}

