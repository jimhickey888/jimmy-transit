/* Live arrivals for green minibus 25 & 49M and Citybus 25, 25A, 27, 85.
   Data: Transport Department eTA GMB API and data.gov.hk Citybus API.
   Route geometry and saved stops come from data.js (generated by bake.py). */

const GMB_API = 'https://data.etagmb.gov.hk';
const CTB_API = 'https://rt.data.gov.hk';
const REFRESH_MS = 30000;
const MAX_ETAS = 3;
const MOVE_THRESHOLD_M = 20;

const state = {
  etas: new Map(),     // key -> { enabled, desc, list, at }
  nearest: new Map(),  // page id -> { route, stop, dist }
  lastUpdate: null,
  error: false,
  busy: false,
  lastPos: null,
  page: 0,
};

function keyOf(page, route, stop) {
  return page.api === 'gmb'
    ? `gmb:${route.route_id}/${route.route_seq}/${stop.seq}`
    : `ctb:${route.route}/${route.dirCode}/${stop.stop_id}`;
}

const esc = (value) => String(value).replace(/[&<>"']/g, (c) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[c]));

function minutesFrom(entry, now) {
  const t = Date.parse(entry && entry.timestamp);
  if (Number.isFinite(t)) return Math.round((t - now) / 60000);
  if (entry && typeof entry.diff === 'number') return entry.diff;
  return null;
}

function isWholeMinute(iso) {
  const t = Date.parse(iso);
  return Number.isFinite(t) && new Date(t).getSeconds() === 0;
}

function sortedEntries(list, now) {
  return list
    .map((entry) => {
      const m = minutesFrom(entry, now);
      if (m === null) return null;
      return { m, scheduled: !!entry.scheduled };
    })
    .filter(Boolean)
    .sort((a, b) => a.m - b.m);
}

function fmtTime(date) {
  return date.toLocaleTimeString('en-GB', { hour12: false });
}

function fmtDistance(metres) {
  if (metres < 1000) return `${Math.max(10, Math.round(metres / 10) * 10)} m`;
  return `${(metres / 1000).toFixed(1)} km`;
}

function distanceM(a, b) {
  const R = 6371000;
  const rad = (x) => (x * Math.PI) / 180;
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
    + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/* ---------------- data ---------------- */

async function getJson(url, signal) {
  const res = await fetch(url, { cache: 'no-store', signal });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

/* Citybus publishes ETAs per stop, not per route. The batch Stop-ETA
   endpoint is the one that carries live data; the per-route endpoint
   returns an empty list. One request covers every route at a stop, so
   results are shared between cards and reused for a few seconds. */
const CTB_STOP_TTL = 8000;
const ctbStops = new Map(); // stop_id -> { at, promise }

function ctbStopEta(stopId) {
  const now = Date.now();
  const hit = ctbStops.get(stopId);
  if (hit && now - hit.at < CTB_STOP_TTL) return hit.promise;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 12000);
  const promise = getJson(`${CTB_API}/v1/transport/batch/stop-eta/CTB/${stopId}`, controller.signal)
    .then((body) => (Array.isArray(body.data) ? body.data : []))
    .finally(() => clearTimeout(timer));

  ctbStops.set(stopId, { at: now, promise });
  promise.catch(() => ctbStops.delete(stopId));
  return promise;
}

async function fetchEta(page, route, stop) {
  const key = keyOf(page, route, stop);

  if (page.api === 'gmb') {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 12000);
    try {
      const body = await getJson(
        `${GMB_API}/eta/route-stop/${route.route_id}/${route.route_seq}/${stop.seq}`,
        controller.signal,
      );
      const data = body.data || {};
      state.etas.set(key, {
        enabled: data.enabled !== false,
        desc: data.description_en || '',
        list: Array.isArray(data.eta) ? data.eta : [],
        at: Date.now(),
      });
    } finally {
      clearTimeout(timer);
    }
    return;
  }

  const rows = await ctbStopEta(stop.stop_id);
  /* Match on stop sequence rather than the direction flag: Citybus labels
     the direction inconsistently, but `seq` follows the route-stop list.
     A few poles serve both directions, so keep the one arriving soonest
     and label the card with where those buses are going. */
  const matched = rows
    .filter((row) => row.route === route.route && row.seq === stop.seq && row.eta)
    .sort((a, b) => Date.parse(a.eta) - Date.parse(b.eta));

  const dest = matched.length ? (matched[0].dest || '') : '';
  const list = matched
    .filter((row) => (row.dest || '') === dest)
    .map((row) => ({
      timestamp: row.eta,
      remarks: row.rmk || '',
      /* Citybus has no scheduled/live flag in the open data. A scheduled
         trip is published on the exact minute; live GPS predictions carry
         seconds. */
      scheduled: isWholeMinute(row.eta),
    }));

  state.etas.set(key, { enabled: true, desc: '', dest, list, at: Date.now() });
}

async function refresh(force = false) {
  if (state.busy) return;
  if (!force && state.lastUpdate && Date.now() - state.lastUpdate.getTime() < 5000) return;
  if (force) ctbStops.clear();
  state.busy = true;
  setBusy(true);

  const jobs = new Map();
  for (const page of PAGES) {
    for (const route of page.routes) {
      for (const stop of route.bookmarks) {
        jobs.set(keyOf(page, route, stop), { page, route, stop });
      }
    }
    const near = state.nearest.get(page.id);
    if (near) {
      jobs.set(keyOf(page, near.route, near.stop), { page, route: near.route, stop: near.stop });
    }
  }

  const results = await Promise.allSettled(
    [...jobs.values()].map(({ page, route, stop }) => fetchEta(page, route, stop)),
  );

  state.error = results.length > 0 && results.every((r) => r.status === 'rejected');
  state.lastUpdate = new Date();
  state.busy = false;
  setBusy(false);
  render();
}

/* ---------------- nearest stop ---------------- */

function computeNearest(page, pos) {
  let best = null;
  const seen = new Set();

  for (const route of page.routes) {
    for (const stop of route.stops) {
      if (seen.has(stop.stop_id)) continue;
      seen.add(stop.stop_id);
      if (typeof stop.lat !== 'number' || typeof stop.lon !== 'number') continue;
      const dist = distanceM(pos, { lat: stop.lat, lon: stop.lon });
      if (!best || dist < best.dist) best = { route, stop, dist };
    }
  }
  return best;
}

async function updateNearest(pos) {
  for (const page of PAGES) {
    const next = computeNearest(page, pos);
    if (!next) continue;

    const prev = state.nearest.get(page.id);
    const changed = !prev || prev.route !== next.route || prev.stop !== next.stop;
    state.nearest.set(page.id, next);
    if (!changed) continue;

    const cached = state.etas.get(keyOf(page, next.route, next.stop));
    if (!cached || Date.now() - cached.at > REFRESH_MS - 5000) {
      fetchEta(page, next.route, next.stop).catch(() => {
        /* keep showing the strip without a time */
      });
    }
  }
  render();
}

function startGeolocation() {
  if (!('geolocation' in navigator)) return;

  navigator.geolocation.watchPosition(
    (position) => {
      const pos = {
        lat: position.coords.latitude,
        lon: position.coords.longitude,
      };
      if (state.lastPos && distanceM(state.lastPos, pos) < MOVE_THRESHOLD_M) return;
      state.lastPos = pos;
      updateNearest(pos);
    },
    () => {
      if (state.nearest.size) {
        state.nearest.clear();
        render();
      }
    },
    { enableHighAccuracy: true, maximumAge: 60000, timeout: 20000 },
  );
}

/* ---------------- rendering ---------------- */

function etasHtml(page, route, stop) {
  const cached = state.etas.get(keyOf(page, route, stop));

  if (!cached) return '<span class="empty">Loading…</span>';
  if (!cached.enabled) return `<span class="empty">${esc(cached.desc || 'Not available')}</span>`;

  const entries = sortedEntries(cached.list, Date.now()).slice(0, MAX_ETAS);
  if (!entries.length) return '<span class="empty">No arrivals right now</span>';

  return entries.map(({ m, scheduled }, i) => {
    const classes = ['eta'];
    if (scheduled) classes.push('sched');
    else if (i === 0) classes.push('first');
    if (m <= 0 && !scheduled) classes.push('due');

    const cls = classes.join(' ');
    const title = scheduled ? 'Scheduled time' : 'Live arrival';

    if (m <= 0) return `<span class="${cls}" title="${title}">Due</span>`;
    return `<span class="${cls}" title="${title}"><b>${m}</b><small>min</small></span>`;
  }).join('');
}

function destHtml(page, route, stop) {
  if (page.api !== 'ctb') return '';
  const cached = state.etas.get(keyOf(page, route, stop));
  if (!cached || !cached.dest) return '';
  return `<div class="stop-dest">→ ${esc(cached.dest)}</div>`;
}

function nearestHtml(page) {
  const near = state.nearest.get(page.id);
  if (!near) return '';

  const { route, stop, dist } = near;
  const cached = state.etas.get(keyOf(page, route, stop));
  let eta = '…';
  let scheduled = false;

  if (cached) {
    if (!cached.enabled) {
      eta = '—';
    } else {
      const entries = sortedEntries(cached.list, Date.now());
      if (!entries.length) {
        eta = '—';
      } else {
        eta = entries[0].m <= 0 ? 'Due' : `${entries[0].m} min`;
        scheduled = entries[0].scheduled;
      }
    }
  }

  return `
    <div class="nearest">
      <svg class="pin" viewBox="0 0 24 24" fill="none" stroke="currentColor"
           stroke-width="1.8" stroke-linejoin="round" aria-hidden="true">
        <path d="M12 21s-6.5-5.8-6.5-10.5a6.5 6.5 0 1 1 13 0C18.5 15.2 12 21 12 21z"/>
        <circle cx="12" cy="10.4" r="2.3"/>
      </svg>
      <div class="nearest-main">
        <div class="nearest-stop">${esc(route.code)} · ${esc(stop.name)}</div>
        <div class="nearest-dist">${fmtDistance(dist)} away</div>
      </div>
      <div class="nearest-eta${scheduled ? ' sched' : ''}">${esc(eta)}</div>
    </div>`;
}

function sourceLine(page) {
  return page.api === 'gmb'
    ? 'Real-time data from the Transport Department<br>eTA GMB service'
    : 'Real-time data from data.gov.hk<br>Citybus';
}

function renderPage(page) {
  const el = document.getElementById(`body-${page.id}`);
  if (!el) return;

  let html = nearestHtml(page);

  for (const route of page.routes) {
    html += `
      <section class="route">
        <div class="route-head">
          <span class="badge">${esc(route.code)}</span>
          <span class="route-desc">${esc(route.orig)} → ${esc(route.dest)}</span>
        </div>`;

    for (const stop of route.bookmarks) {
      html += `
        <article class="card">
          <div class="card-top">
            <div class="stop-head">
              <div class="stop-name">${esc(stop.name)}</div>
              ${destHtml(page, route, stop)}
            </div>
            <div class="stop-seq">Stop ${stop.seq}</div>
          </div>
          <div class="etas">${etasHtml(page, route, stop)}</div>
        </article>`;
    }

    html += '</section>';
  }

  html += `<footer class="foot"><p>${sourceLine(page)}</p></footer>`;
  el.innerHTML = html;
}

function renderStatus() {
  const dot = document.getElementById('dot');
  const label = document.getElementById('updated');

  if (state.error) {
    dot.className = 'dot err';
    label.textContent = 'Connection problem · retrying';
    return;
  }
  if (!state.lastUpdate) {
    dot.className = 'dot';
    label.textContent = 'Connecting…';
    return;
  }

  const age = (Date.now() - state.lastUpdate.getTime()) / 1000;
  dot.className = `dot ${age < REFRESH_MS + 45 ? 'live' : 'stale'}`;
  label.textContent = `Live · updated ${fmtTime(state.lastUpdate)}`;
}

function render() {
  for (const page of PAGES) renderPage(page);
  renderStatus();
}

function setBusy(busy) {
  const button = document.getElementById('refresh');
  button.classList.toggle('spin', busy);
  button.disabled = busy;
}

/* ---------------- paging ---------------- */

function pagerEl() {
  return document.getElementById('pager');
}

function currentIndex() {
  const el = pagerEl();
  if (!el.clientWidth) return 0;
  return Math.max(0, Math.min(PAGES.length - 1, Math.round(el.scrollLeft / el.clientWidth)));
}

function goToPage(index, smooth = true) {
  const el = pagerEl();
  el.scrollTo({ left: index * el.clientWidth, behavior: smooth ? 'smooth' : 'auto' });
}

function syncChrome() {
  state.page = currentIndex();
  const page = PAGES[state.page];
  if (!page) return;

  document.getElementById('title').textContent = page.title;
  document.getElementById('sub').textContent = page.routes.map((r) => r.code).join(' · ');
  document.title = `${page.title} · Bus Times`;

  const dots = document.querySelectorAll('.pdot');
  dots.forEach((dot, i) => {
    dot.classList.toggle('on', i === state.page);
    if (i === state.page) dot.setAttribute('aria-current', 'page');
    else dot.removeAttribute('aria-current');
  });
}

function buildPager() {
  const pager = pagerEl();
  pager.innerHTML = PAGES.map((page) => `
    <section class="page" aria-label="${esc(page.title)}">
      <div class="page-inner" id="body-${page.id}"></div>
    </section>`).join('');

  const dots = document.getElementById('pdots');
  dots.innerHTML = PAGES.map((page, i) => `
    <button class="pdot" type="button" data-index="${i}"
            aria-label="Show ${esc(page.title)}"></button>`).join('');

  dots.addEventListener('click', (event) => {
    const button = event.target.closest('.pdot');
    if (!button) return;
    goToPage(Number(button.dataset.index));
  });

  let ticking = false;
  pager.addEventListener('scroll', () => {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(() => {
      ticking = false;
      syncChrome();
    });
  }, { passive: true });

  window.addEventListener('resize', () => goToPage(state.page, false));
}

/* ---------------- boot ---------------- */

function init() {
  buildPager();
  syncChrome();
  render();

  document.getElementById('refresh').addEventListener('click', () => refresh(true));

  startGeolocation();
  refresh();

  setInterval(() => {
    if (document.visibilityState === 'visible') refresh();
  }, REFRESH_MS);

  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'visible') refresh();
  });

  window.addEventListener('online', () => refresh(true));

  const secure = location.protocol === 'https:'
    || location.hostname === 'localhost'
    || location.hostname === '127.0.0.1';

  if ('serviceWorker' in navigator && secure) {
    navigator.serviceWorker.register('sw.js').catch(() => {});
  }
}

document.addEventListener('DOMContentLoaded', init);
