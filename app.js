/* ---------------- tracked arrival ---------------- */

function registerPill(pill) {
  const id = String(++state.pillSeq);
  state.pills.set(id, pill);
  return id;
}

function isTrackedPill(pill) {
  const t = state.tracked;
  if (!t || !pill) return false;
  return t.routeCode === pill.routeCode
    && t.stopId === pill.stopId
    && Math.abs(t.targetMs - pill.targetMs) < 90000;
}

function saveTracked() {
  try {
    if (state.tracked) localStorage.setItem(TRACK_KEY, JSON.stringify(state.tracked));
    else localStorage.removeItem(TRACK_KEY);
  } catch { /* storage may be full or blocked */ }
}

function savePrefs() {
  try { localStorage.setItem(PREFS_KEY, JSON.stringify(state.prefs)); } catch { /* ignore */ }
}

/* Keep the last good arrivals so a cold start paints immediately. */
function saveSnapshot() {
  if (!state.etas.size) return;
  try {
    const etas = [...state.etas.entries()].map(([key, value]) => [key, {
      enabled: value.enabled,
      desc: value.desc || '',
      dest: value.dest || '',
      list: value.list,
      at: value.at,
    }]);
    localStorage.setItem(SNAP_KEY, JSON.stringify({ at: Date.now(), etas }));
  } catch { /* quota or private mode */ }
}

function loadSnapshot() {
  try {
    const snap = JSON.parse(localStorage.getItem(SNAP_KEY) || 'null');
    if (!snap || !Array.isArray(snap.etas)) return false;
    if (Date.now() - Number(snap.at) > SNAP_MAX_AGE) return false;
    for (const [key, value] of snap.etas) {
      if (value && Array.isArray(value.list)) state.etas.set(key, value);
    }
    state.fromCache = state.etas.size > 0;
    return state.fromCache;
  } catch {
    return false;
  }
}

/* The tracked arrival lives in one of two caches: a normal stop group or a
   Taikoo segment direction. */
function trackedList(t) {
  if (!t || !t.source) return null;
  if (t.source.type === 'segment') {
    const cache = state.segments.get(t.source.key);
    const side = cache && cache[t.source.field];
    return side ? side.list : null;
  }
  const cache = state.etas.get(t.source.key);
  return cache ? cache.list : null;
}

/* Live predictions drift by a few seconds on every poll. Adopt the refreshed
   time when it is clearly the same bus. */
function syncTracked() {
  const t = state.tracked;
  if (!t) return;
  const list = trackedList(t);
  if (!Array.isArray(list) || !list.length) return;

  let best = null;
  for (const entry of list) {
    const ms = Date.parse(entry && entry.timestamp);
    if (!Number.isFinite(ms)) continue;
    const diff = Math.abs(ms - t.targetMs);
    if (diff <= 180000 && (!best || diff < best.diff)) best = { entry, ms, diff };
  }
  if (!best) return;

  const shifted = Math.abs(best.ms - t.targetMs) > 1000;
  const previous = t.targetMs;
  t.targetMs = best.ms;
  t.timestamp = best.entry.timestamp;
  t.timeZone = best.entry.timeZone || t.timeZone;
  t.scheduled = !!best.entry.scheduled;
  t.vehicle = best.entry.vehicle || '';
  saveTracked();

  /* Only re-arm when the prediction really moved, otherwise the app would
     rewrite six alerts every 30 seconds. */
  if (shifted && t.alert && t.alert.active && Math.abs(best.ms - previous) > 60000) {
    rescheduleAlert();
  }
}

async function rescheduleAlert() {
  const t = state.tracked;
  if (!t || !t.alert || !t.alert.active) return;
  try {
    const sub = state.pushSub || await ensurePushSubscription();
    await scheduleAlert(sub);
  } catch { /* keep the old schedule */ }
}

/* Every milestone fires one minute early, so the "10 min" alert lands at
   11 minutes before the arrival and "due" lands one minute before. */
const ALERT_LEAD_MS = 60000;

function alertSteps(targetMs) {
  return ALERT_MINUTES.map((minutes) => ({
    minutes,
    fireAt: targetMs - (minutes + 1) * ALERT_LEAD_MS,
  }));
}

function alertPlan(targetMs) {
  const now = Date.now();
  return alertSteps(targetMs).filter((step) => step.fireAt > now + 20000);
}

/* Marks already in the past when tracking starts must not beep. */
function resetBeeps(targetMs) {
  const left = targetMs - Date.now();
  const fired = {};
  for (const mark of IN_APP_MARKS) {
    if (left <= mark * 1000) fired[mark] = true;
  }
  return fired;
}

function toggleTracked(pill) {
  if (!pill) return;
  if (isTrackedPill(pill)) {
    clearTracked();
    return;
  }
  /* Switching to another bus must cancel the previous pending alerts,
     otherwise they would still arrive for a bus you no longer track. */
  if (state.tracked && state.tracked.alert && state.tracked.alert.active) {
    cancelAlert(state.tracked.alert.ids);
  }
  state.tracked = {
    routeCode: pill.routeCode,
    stopId: pill.stopId,
    stopName: pill.stopName,
    direction: pill.direction || '',
    pageId: pill.pageId || '',
    source: pill.source,
    timestamp: pill.timestamp,
    timeZone: pill.timeZone || '',
    targetMs: pill.targetMs,
    scheduled: !!pill.scheduled,
    vehicle: pill.vehicle || '',
    screenOn: !!state.prefs.screenOn,
    beep: true,
    alert: null,
  };
  state.beeps = resetBeeps(pill.targetMs);
  unlockAudio();
  saveTracked();
  ensureTrackedTimer();
  render();
  applyWakeLock();
  if (pushConfigured() && Notification.permission === 'granted'
      && alertPlan(pill.targetMs).length) {
    ensurePushSubscription().then(scheduleAlert).catch(() => {});
  }
}

function clearTracked() {
  const t = state.tracked;
  if (t && t.alert && t.alert.active) cancelAlert(t.alert.ids);
  state.tracked = null;
  state.beeps = {};
  saveTracked();
  ensureTrackedTimer();
  releaseWakeLock();
  render();
}

function fmtCountdown(ms) {
  if (ms <= 0) return 'Due';
  const total = Math.ceil(ms / 1000);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  if (h) return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
  return `${m}:${String(s).padStart(2, '0')}`;
}

function alertChipLabel(t) {
  if (t.alert && t.alert.active) return 'Alerts on · 10→0';
  if (!pushSupported()) return 'Alerts need Home Screen';
  if (typeof Notification !== 'undefined' && Notification.permission === 'denied') return 'Alerts blocked';
  return 'Alerts 10 → 0 min';
}

function trackedHtml(t) {
  const chips = pushConfigured()
    ? `<button class="chip" type="button" data-tracked="alert"
         aria-pressed="${!!(t.alert && t.alert.active)}">${esc(alertChipLabel(t))}</button>`
    : '';
  return `
    <div class="tracked-row">
      <span class="badge">${esc(t.routeCode)}</span>
      <span class="tracked-dir">${esc(t.direction || 'Tracked arrival')}</span>
      <button class="tracked-close" type="button" data-tracked="clear" aria-label="Stop tracking">×</button>
    </div>
    <div class="tracked-row tracked-lower">
      <span class="tracked-sub">${esc(t.stopName || '')}${t.stopId ? ` · Stop ${esc(t.stopId)}` : ''}</span>
      <span class="tracked-clock">
        <span class="tracked-count" id="trackedCount">--:--</span>
        <span class="tracked-at" id="trackedAt">${esc(fmtClock(new Date(t.targetMs), t.timeZone))}</span>
      </span>
    </div>
    <div class="tracked-row tracked-chips">
      ${chips}
      <button class="chip" type="button" data-tracked="screen"
        aria-pressed="${!!t.screenOn}">Keep screen on</button>
    </div>`;
}

function renderTracked() {
  const bar = document.getElementById('tracked');
  if (!bar) return;
  const t = state.tracked;
  if (!t) {
    bar.hidden = true;
    bar.innerHTML = '';
    bar.classList.remove('urgent');
    return;
  }
  bar.hidden = false;
  bar.innerHTML = trackedHtml(t);
  tickTracked();
}

let trackedTimer = null;

function ensureTrackedTimer() {
  if (state.tracked && !trackedTimer) {
    trackedTimer = setInterval(tickTracked, 1000);
  } else if (!state.tracked && trackedTimer) {
    clearInterval(trackedTimer);
    trackedTimer = null;
  }
}

function tickTracked() {
  const t = state.tracked;
  if (!t) return;
  const count = document.getElementById('trackedCount');
  if (!count) {
    renderTracked();
    return;
  }
  const left = t.targetMs - Date.now();
  count.textContent = fmtCountdown(left);
  count.classList.toggle('due', left <= 0);
  document.getElementById('tracked').classList.toggle('urgent', left <= 60000);

  if (t.beep) {
    let crossed = null;
    for (const mark of IN_APP_MARKS) {
      if (!state.beeps[mark] && left <= mark * 1000) {
        state.beeps[mark] = true;
        crossed = mark;
      }
    }
    if (crossed !== null) {
      beep(crossed === 0 ? 3 : 2);
      pulseTracked();
    }
  }

  if (left < -120000) clearTracked();
}

let flashTimer = null;
let pulseTimer = null;

/* Briefly flash the tracked bar when a countdown milestone passes. */
function pulseTracked() {
  const bar = document.getElementById('tracked');
  if (!bar) return;
  bar.classList.remove('pulse');
  void bar.offsetWidth;
  bar.classList.add('pulse');
  clearTimeout(pulseTimer);
  pulseTimer = setTimeout(() => bar.classList.remove('pulse'), 1600);
}

function flashChip(text) {
  const chip = document.querySelector('#tracked .chip[data-tracked="alert"]');
  if (!chip) return;
  chip.textContent = text;
  chip.disabled = true;
  clearTimeout(flashTimer);
  flashTimer = setTimeout(() => {
    chip.disabled = false;
    renderTracked();
  }, 2600);
}

/* ---------------- sound and screen ---------------- */

let audioCtx = null;

function unlockAudio() {
  const Ctor = window.AudioContext || window.webkitAudioContext;
  if (!Ctor) return;
  try {
    audioCtx = audioCtx || new Ctor();
    if (audioCtx.state === 'suspended') audioCtx.resume();
  } catch {
    audioCtx = null;
  }
}

function beep(count) {
  if (!audioCtx) return;
  try {
    const now = audioCtx.currentTime;
    for (let i = 0; i < count; i += 1) {
      const at = now + i * 0.22;
      const osc = audioCtx.createOscillator();
      const gain = audioCtx.createGain();
      osc.type = 'sine';
      osc.frequency.value = 880;
      gain.gain.setValueAtTime(0.0001, at);
      gain.gain.exponentialRampToValueAtTime(0.2, at + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.0001, at + 0.16);
      osc.connect(gain).connect(audioCtx.destination);
      osc.start(at);
      osc.stop(at + 0.18);
    }
  } catch { /* audio is best effort */ }
}

async function applyWakeLock() {
  const want = state.tracked && state.tracked.screenOn;
  if (!want) {
    releaseWakeLock();
    return;
  }
  if (!('wakeLock' in navigator) || document.visibilityState !== 'visible') return;
  try {
    if (!state.wakeLock) {
      state.wakeLock = await navigator.wakeLock.request('screen');
      state.wakeLock.addEventListener('release', () => { state.wakeLock = null; });
    }
  } catch {
    state.wakeLock = null;
  }
}

function releaseWakeLock() {
  if (state.wakeLock) {
    try { state.wakeLock.release(); } catch { /* already gone */ }
    state.wakeLock = null;
  }
}

function toggleScreen() {
  const t = state.tracked;
  if (!t) return;
  t.screenOn = !t.screenOn;
  state.prefs.screenOn = t.screenOn;
  savePrefs();
  saveTracked();
  applyWakeLock();
  renderTracked();
  if (t.screenOn && !('wakeLock' in navigator)) flashChip('Screen wake lock unsupported');
}

/* ---------------- push alerts (optional) ---------------- */

function pushConfigured() {
  return Boolean(PUSH_ENDPOINT && PUSH_VAPID_KEY);
}

function pushSupported() {
  return 'Notification' in window && 'PushManager' in window && 'serviceWorker' in navigator;
}

function b64urlToBytes(value) {
  const padded = value.replace(/-/g, '+').replace(/_/g, '/');
  const raw = atob(padded + '='.repeat((4 - (padded.length % 4)) % 4));
  return Uint8Array.from(raw, (c) => c.charCodeAt(0));
}

async function ensurePushSubscription() {
  const reg = await navigator.serviceWorker.ready;
  let sub = await reg.pushManager.getSubscription();
  if (!sub) {
    sub = await reg.pushManager.subscribe({
      userVisibleOnly: true,
      applicationServerKey: b64urlToBytes(PUSH_VAPID_KEY),
    });
  }
  state.pushSub = sub;
  return sub;
}

async function armAlert() {
  const t = state.tracked;
  if (!t) return;
  if (!pushConfigured()) {
    flashChip('Push not set up yet');
    return;
  }
  if (!pushSupported()) {
    flashChip('Add to Home Screen first');
    return;
  }
  if (Notification.permission === 'denied') {
    flashChip('Notifications blocked');
    return;
  }

  if (t.alert && t.alert.active) {
    cancelAlert(t.alert.ids);
    t.alert = null;
    saveTracked();
    renderTracked();
    return;
  }

  const plan = alertPlan(t.targetMs);
  if (!plan.length) {
    flashChip('Too close for alerts');
    return;
  }

  const permissionGranted = Notification.permission === 'granted';
  const permission = permissionGranted
    ? 'granted'
    : await Notification.requestPermission();
  if (permission !== 'granted') {
    flashChip('Alerts not allowed');
    return;
  }

  /* iOS ties push subscriptions to a tap; after a fresh permission prompt
     ask for one more tap so subscribe() runs inside its own gesture. */
  if (!permissionGranted) {
    flashChip('Tap again to enable alerts');
    return;
  }

  try {
    const sub = state.pushSub || await ensurePushSubscription();
    await scheduleAlert(sub);
  } catch {
    flashChip('Could not set alert');
  }
}

function alertBody(t) {
  return [t.stopName, t.stopId ? `Stop ${t.stopId}` : '', t.direction]
    .filter(Boolean).join(' · ');
}

/* One alert per milestone still ahead: 10, 8, 6, 4, 2 and 0 minutes.
   The worker stores them separately and its cron sends each in turn. */
async function scheduleAlert(sub) {
  const t = state.tracked;
  if (!t) return;

  const now = Date.now();
  const previous = t.alert && t.alert.active && t.alert.fires ? t.alert.fires : null;
  const steps = [];

  for (const step of alertSteps(t.targetMs)) {
    if (step.fireAt > now + 20000) {
      steps.push(step);
      continue;
    }
    const previousFire = previous ? previous[step.minutes] : undefined;
    /* The arrival moved earlier and passed a milestone that was still ahead
       at the last schedule: send it now instead of skipping it. */
    if (previous && previousFire !== undefined && previousFire > now) {
      steps.push({ ...step, fireAt: now + 15000, catchUp: true });
    }
  }

  if (!steps.length) {
    t.alert = null;
    saveTracked();
    renderTracked();
    return;
  }

  /* Re-opening the app should not rewrite an unchanged schedule; that was
     costing six alert writes plus a subscription write per launch. */
  const unchanged = previous
    && steps.length === Object.keys(previous).length
    && steps.every((step) => Number(previous[step.minutes]) === Number(step.fireAt));
  if (unchanged && Date.now() - (t.alert.postedAt || 0) < 6 * 60 * 60 * 1000) {
    return;
  }

  const group = (t.alert && t.alert.group)
    || `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`;
  const subscription = sub && sub.toJSON ? sub.toJSON() : sub;
  const body = alertBody(t);
  const alerts = steps.map((step) => {
    const id = `${group}-${step.minutes}`;
    return {
      id,
      fireAt: step.fireAt,
      leadMinutes: step.minutes,
      title: step.minutes === 0
        ? `${t.routeCode} due now`
        : `${t.routeCode} in ${step.minutes} min`,
      body,
      tag: id,
    };
  });
  const ids = alerts.map((alert) => alert.id);

  try {
    noteApiCall(PUSH_LABEL);
    let res = await fetch(`${PUSH_ENDPOINT}/alerts`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ subscription, alerts }),
    });

    /* Older workers only expose the single-alert endpoint. */
    if (res.status === 404 || res.status === 405) {
      for (const alert of alerts) {
        noteApiCall(PUSH_LABEL);
        res = await fetch(`${PUSH_ENDPOINT}/alert`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ subscription, alert }),
        });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
      }
    } else if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }
  } catch (error) {
    /* Do not leave a half-armed group behind. */
    cancelAlert(ids);
    throw error;
  }

  const fires = {};
  for (const step of steps) fires[step.minutes] = step.fireAt;

  t.alert = {
    group,
    ids,
    minutes: steps.map((step) => step.minutes),
    fires,
    active: true,
    postedAt: Date.now(),
  };
  saveTracked();
  renderTracked();
}

function cancelAlert(ids) {
  if (!pushConfigured() || !ids) return;
  const list = Array.isArray(ids) ? ids : [ids];
  for (const id of list) {
    noteApiCall(PUSH_LABEL);
    fetch(`${PUSH_ENDPOINT}/alert?id=${encodeURIComponent(id)}`, { method: 'DELETE' })
      .catch(() => {});
  }
}

/* Re-arm an existing alert when the app opens, so a stale fire time is
   refreshed and the subscription is kept alive. */
async function restoreAlert() {
  const t = state.tracked;
  if (!t || !t.alert || !t.alert.active) return;
  if (!pushConfigured() || !pushSupported()) return;
  if (Notification.permission !== 'granted') return;
  try {
    const sub = state.pushSub || await ensurePushSubscription();
    await scheduleAlert(sub);
  } catch { /* the old schedule in KV still stands */ }
}

/* ---------------- paging ---------------- */

function pagerEl() {
  return document.getElementById('pager');
}

function currentIndex() {
  const el = pagerEl();
  if (!el.clientWidth) return 0;
  return Math.max(0, Math.min(PAGES.length - 1, Math.round(el.scrollLeft / el.clientWidth)));
}

function goToPage(index, smooth = true) {
  const el = pagerEl();
  el.scrollTo({ left: index * el.clientWidth, behavior: smooth ? 'smooth' : 'auto' });
}

function syncChrome() {
  state.page = currentIndex();
  const page = PAGES[state.page];
  if (!page) return;

  document.getElementById('title').textContent = page.title;
  const brand = document.getElementById('brand');
  if (brand) brand.innerHTML = BRAND_MARKS[page.id] || BRAND_MARKS.info;
  const codes = page.routes
    ? [...new Set(page.routes.map((r) => r.code))]
    : [];
  document.getElementById('sub').textContent = page.subtitle || codes.join(' · ');
  document.title = `${page.title} · Jimmy Transit Tracker`;

  scheduleActivation();

  if (state.savedPage !== state.page) {
    state.savedPage = state.page;
    try { localStorage.setItem(PAGE_KEY, String(state.page)); } catch { /* ignore */ }
    /* Refresh the counters each time the Info page is opened. */
    if (page.api === 'info') renderPage(page);
  }

  const tabs = document.querySelectorAll('.tab');
  tabs.forEach((tab, i) => {
    const active = i === state.page;
    tab.classList.toggle('on', active);
    if (active) tab.setAttribute('aria-current', 'page');
    else tab.removeAttribute('aria-current');
  });

  if (state.tabShown !== state.page) {
    state.tabShown = state.page;
    const nav = document.getElementById('tabs');
    const activeTab = nav && nav.children[state.page];
    if (nav && activeTab) {
      const left = activeTab.offsetLeft - (nav.clientWidth - activeTab.clientWidth) / 2;
      nav.scrollTo({ left: Math.max(0, left), behavior: 'smooth' });
    }
  }
}

function buildPager() {
  const pager = pagerEl();
  pager.innerHTML = PAGES.map((page) => `
    <section class="page" aria-label="${esc(page.title)}">
      <div class="page-inner" id="body-${page.id}"></div>
    </section>`).join('');

  /* Defensive: if an older cached shell is served with a newer app.js, add
     the tab bar instead of failing on a missing element. */
  let tabs = document.getElementById('tabs');
  if (!tabs) {
    tabs = document.createElement('nav');
    tabs.id = 'tabs';
    tabs.className = 'tabs';
    tabs.setAttribute('aria-label', 'Pages');
    const statusline = document.querySelector('.statusline');
    if (statusline) statusline.after(tabs);
    else document.querySelector('#app').prepend(tabs);
  }

  tabs.innerHTML = PAGES.map((page, i) => `
    <button class="tab" type="button" data-index="${i}"
            ${i === 0 ? 'aria-current="page"' : ''}>${esc(page.title)}</button>`).join('');

  tabs.addEventListener('click', (event) => {
    const button = event.target.closest('.tab');
    if (!button) return;
    const index = Number(button.dataset.index);
    if (index === state.page) return;
    goToPage(index);
  });

  let ticking = false;
  pager.addEventListener('scroll', () => {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(() => {
      ticking = false;
      syncChrome();
    });
  }, { passive: true });

  pager.addEventListener('click', (event) => {
    const pill = event.target.closest('.eta[data-pill]');
    if (!pill) return;
    const ctx = state.pills.get(pill.dataset.pill);
    if (ctx) toggleTracked(ctx);
  });

  window.addEventListener('resize', () => goToPage(state.page, false));
}

/* ---------------- boot ---------------- */

function readSavedPage() {
  try {
    const saved = Number(localStorage.getItem(PAGE_KEY) || '0');
    return Number.isInteger(saved) ? saved : 0;
  } catch {
    return 0;
  }
}

function restorePage(index, done) {
  if (!Number.isInteger(index) || index <= 0 || index >= PAGES.length) {
    if (done) done();
    return;
  }
  let tries = 3;
  /* On a cold launch the pager can still have zero width for a frame or two
     on iOS, which would silently drop the scroll. */
  const place = () => {
    if (pagerEl().clientWidth > 0) {
      goToPage(index, false);
      syncChrome();
      if (done) done();
      return;
    }
    if (tries-- > 0) {
      requestAnimationFrame(place);
    } else if (done) {
      done();
    }
  };
  requestAnimationFrame(place);
}

function init() {
  loadInstallCalls();
  loadSnapshot();
  const savedPage = readSavedPage();
  buildPager();
  /* Jump before the first syncChrome so only the restored page loads. */
  if (savedPage > 0 && savedPage < PAGES.length) goToPage(savedPage, false);
  syncChrome();
  render();

  document.getElementById('refresh').addEventListener('click', () => refresh(true));

  /* Unlock WebAudio on the first tap so a countdown restored from a previous
     launch can beep without tapping the tracked arrival again. */
  document.addEventListener('pointerdown', unlockAudio, { once: true, passive: true });

  document.getElementById('tracked').addEventListener('click', (event) => {
    const button = event.target.closest('[data-tracked]');
    if (!button) return;
    const action = button.dataset.tracked;
    if (action === 'clear') clearTracked();
    else if (action === 'alert') armAlert();
    else if (action === 'screen') toggleScreen();
  });

  startGeolocation();
  restoreAlert();
  if (savedPage > 0 && currentIndex() !== savedPage) {
    restorePage(savedPage, () => {
      activateCurrentPage();
      refresh();
    });
  } else {
    activateCurrentPage();
    refresh();
  }

  ensureTrackedTimer();

  setInterval(() => {
    if (document.visibilityState === 'visible') refresh();
  }, REFRESH_MS);

  setInterval(() => {
    if (document.visibilityState === 'visible') refreshAges();
  }, 30000);

  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'visible') {
      tickTracked();
      if (state.tracked) syncTracked();
      applyWakeLock();
      startGeolocation();
      refresh();
    } else {
      stopGeolocation();
      flushInstallCalls();
    }
  });

  window.addEventListener('pagehide', flushInstallCalls);

  window.addEventListener('online', () => refresh(true));

  /* iOS can invalidate a push subscription. Drop the stale schedule and
     re-arm with the fresh one. */
  if ('serviceWorker' in navigator) {
    navigator.serviceWorker.addEventListener('message', (event) => {
      if (!event.data || event.data.type !== 'push-subscription-change') return;
      state.pushSub = null;
      if (!state.tracked || !state.tracked.alert || !state.tracked.alert.active) return;
      state.tracked.alert = null;
      saveTracked();
      renderTracked();
      if (pushConfigured() && Notification.permission === 'granted') {
        ensurePushSubscription().then(scheduleAlert).catch(() => {});
      }
    });
  }

  const secure = location.protocol === 'https:'
    || location.hostname === 'localhost'
    || location.hostname === '127.0.0.1';

  if ('serviceWorker' in navigator && secure) {
    navigator.serviceWorker.register('sw.js', { updateViaCache: 'none' }).catch(() => {});
  }
}

document.addEventListener('DOMContentLoaded', init);
