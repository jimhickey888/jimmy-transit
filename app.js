function minutesFrom(entry, now) {
  const t = Date.parse(entry && entry.timestamp);
  if (Number.isFinite(t)) return Math.round((t - now) / 60000);
  if (entry && typeof entry.diff === 'number') return entry.diff;
  return null;
}

function isWholeMinute(iso) {
  const t = Date.parse(iso);
  return Number.isFinite(t) && new Date(t).getSeconds() === 0;
}

function sortedEntries(list, now) {
  return list
    .map((entry) => {
      const m = minutesFrom(entry, now);
      if (m === null) return null;
      return {
        m,
        scheduled: !!entry.scheduled,
        time: clockFrom(entry),
        vehicle: entry.vehicle || '',
        timestamp: entry.timestamp,
        timeZone: entry.timeZone || '',
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.m - b.m);
}

function fmtClock(date, timeZone) {
  const options = {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  };
  if (timeZone) options.timeZone = timeZone;
  return date.toLocaleTimeString('en-GB', options);
}

function clockFrom(entry) {
  const t = Date.parse(entry && entry.timestamp);
  return Number.isFinite(t) ? fmtClock(new Date(t), entry && entry.timeZone) : '';
}

function fmtTime(date) {
  return date.toLocaleTimeString('en-GB', { hour12: false });
}

function fmtDistance(metres) {
  if (metres < 1000) return `${Math.max(10, Math.round(metres / 10) * 10)} m`;
  return `${(metres / 1000).toFixed(1)} km`;
}

function distanceM(a, b) {
  const R = 6371000;
  const rad = (x) => (x * Math.PI) / 180;
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
    + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

